// cjk_font.h —— 中文字库层
//
// 问题：41BB 的 UI 文字用的是 GAF 位图字库，每个字号只有 256 个单字节字形，
// 拿 GBK 双字节去索引必然花屏（这就是主菜单那些 ṪÖ§ṪÖË 的来源）。
//
// 做法：不碰显存、不改游戏文件，把中文当成"运行时生成的贴图帧"喂给引擎自己
// 的绘制管线：
//   1. hook sub_58BF40（单行逐字形 blit）与 sub_58BD70（文本量宽）；
//   2. 遇到 GBK 双字节时，用 GDI 把该汉字画成 8 位索引位图；
//   3. 调 sub_58F6C0 要一个空帧槽、调 sub_58F220 把位图变成纹理帧；
//   4. 用引擎的 vtbl[8]（支持缩放的贴图四边形）画到同样的目标上。
//
// 好处：颜色、缩放、裁剪、渲染目标全部沿用引擎原有逻辑，不需要知道主表面
// 的像素格式，也不会像直接往主表面写像素那样把画面搞花。
